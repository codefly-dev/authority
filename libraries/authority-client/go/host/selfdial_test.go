// judge runs the gate over one adapter package written from sources.
func judge(t *testing.T, sources map[string]string) []string {
	t.Helper()
	root := t.TempDir()
	directory := filepath.Join(root, "svc", "pkg", "adapters")
	if err := os.MkdirAll(directory, 0o755); err != nil {
		t.Fatal(err)
	}
	var violations []string
	agentAdapters := false
	for name, source := range sources {
		path := filepath.Join(directory, name)
		if err := os.WriteFile(path, []byte(source), 0o600); err != nil {
			t.Fatal(err)
		}
		found, agentAdapter := inspect(t, path, "svc/pkg/adapters/"+name)
		violations = append(violations, found...)
		agentAdapters = agentAdapters || agentAdapter
	}
	if agentAdapters {
		violations = append(violations, checkSelfDials(t, root, directory)...)
	}
	return violations
}

