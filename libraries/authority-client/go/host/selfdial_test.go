// agentTemplates are the adapter files the go-grpc agent renders
// (codefly-dev/service-go-grpc templates/factory/code/pkg/adapters/*_gen.go.tmpl).
var agentTemplates = map[string]bool{
	"connect_gen.go": true,
	"cors_gen.go":    true,
	"grpc_gen.go":    true,
	"rest_gen.go":    true,
	"server_gen.go":  true,
}

// agentMarker is the go-grpc agent's generated-code marker. The agent writes it
// instead of the "// Code generated … DO NOT EDIT." line ast.IsGenerated
// recognises, and its own Sync decides which files it owns by it.
const agentMarker = "This code is generated by the agent. Do not edit this file!"

const grpcImport = "google.golang.org/grpc"

var fromEndpoint = regexp.MustCompile(`^Register\w+HandlerFromEndpoint$`)

// isAgentAdapter reports whether file is one of the agent's generated adapters:
// it has one of the agent's template names under a pkg/adapters directory, and
// it carries a generated-code marker (the agent's own, or the standard one)
// before its first declaration. A hand-written *_gen.go is not one.
func isAgentAdapter(file *ast.File, relative string) bool {
	directory, base := path.Split(relative)
	if !agentTemplates[base] || !strings.HasSuffix(strings.TrimSuffix(directory, "/"), "/pkg/adapters") {
		return false
	}
	if ast.IsGenerated(file) {
		return true
	}
	header := file.End()
	if len(file.Decls) > 0 {
		header = file.Decls[0].Pos()
	}
	for _, group := range file.Comments {
		if group.Pos() < header && strings.Contains(group.Text(), agentMarker) {
			return true
		}
	}
	return false
}

// checkSelfDials judges every gRPC dial in the agent's generated adapters of
// one package, type-checked so an identifier is the object it resolves to, not
// its spelling:
//   - each grpc.NewClient, grpc.Dial, grpc.DialContext and
//     Register…HandlerFromEndpoint passes, as its options, a call of the
//     package's gatewayDialOptions, or a local variable whose one and only
//     write is its definition from such a call and whose only uses are dial
//     options arguments or checked generated forwarders (no aliases or escapes);
//   - gatewayDialOptions, declared in a generated adapter, builds its options
//     from a slice literal holding grpc.WithNoProxy() and returns them with
//     grpc.WithTransportCredentials(loopbackTransport{…}) appended last, in
//     straight-line code (no option is set in a branch, a loop or a closure);
//   - loopbackTransport and its ClientHandshake are declared in a generated
//     adapter.
func checkSelfDials(t *testing.T, root, directory string) []string {
	// Real modules need complete type identities, including imported plugin bodies.
	for dir := directory; ; dir = filepath.Dir(dir) {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return loadSelfDialModule(t, root, dir, directory).violations()
		}
		if dir == root || dir == filepath.Dir(dir) {
			break
		}
	}
	// Single-package syntax fixtures deliberately include ill-typed refusals.
	files := token.NewFileSet()
	var parsed []*ast.File
	generated := map[*ast.File]bool{}
	entries, err := os.ReadDir(directory)
	if err != nil {
		t.Fatal(err)
	}
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		full := filepath.Join(directory, name)
		file, err := parser.ParseFile(files, full, nil, parser.ParseComments)
		if err != nil {
			t.Fatalf("%s: %v", full, err)
		}
		relative, _ := filepath.Rel(root, full)
		generated[file] = isAgentAdapter(file, filepath.ToSlash(relative))
		parsed = append(parsed, file)
	}
	c := selfDials{root: root, files: files, generated: generated, info: &types.Info{
		Defs:       map[*ast.Ident]types.Object{},
		Uses:       map[*ast.Ident]types.Object{},
		Selections: map[*ast.SelectorExpr]*types.Selection{},
	}}
	// Imports resolve to empty packages: the check needs the identity of this
	// package's own objects and of the grpc package name, not the imported API,
	// so the type errors that follow are expected and ignored.
	config := types.Config{Importer: emptyPackages{}, Error: func(error) {}}
	c.pkg, _ = config.Check(directory, files, parsed, c.info)
	c.parsed = parsed
	return c.violations()
}

type selfDials struct {
	root      string
	files     *token.FileSet
	parsed    []*ast.File
	generated map[*ast.File]bool
	info      *types.Info
	pkg       *types.Package
	module    map[*types.Package]*selfDials
	refusals  map[string]bool
}

// Preserve the Go tool's environment before TestMain installs its hostile HTTP
// proxy for transport tests. Loading source dependencies is not a host request.
var selfDialToolEnv = os.Environ()

// Load all packages, not just the adapter's import closure: an unregistered
// concrete implementation must be checked too. Type/load errors fail closed.
func loadSelfDialModule(t *testing.T, root, moduleDir, directory string) *selfDials {
	t.Helper()
	loaded, err := packages.Load(&packages.Config{Dir: moduleDir, Env: selfDialToolEnv,
		Mode: packages.LoadSyntax | packages.NeedModule}, "./...")
	if err != nil {
		t.Fatal(err)
	}
	module := map[*types.Package]*selfDials{}
	refusals := map[string]bool{}
	var adapter *selfDials
	for _, pkg := range loaded {
		if len(pkg.Errors) != 0 {
			t.Fatalf("self-dial module type check: %v", pkg.Errors)
		}
		c := &selfDials{root: root, files: pkg.Fset, parsed: pkg.Syntax,
			generated: map[*ast.File]bool{}, info: pkg.TypesInfo, pkg: pkg.Types,
			module: module, refusals: refusals}
		module[pkg.Types] = c
		for _, file := range pkg.Syntax {
			filename := pkg.Fset.Position(file.Pos()).Filename
			relative, _ := filepath.Rel(root, filename)
			c.generated[file] = isAgentAdapter(file, filepath.ToSlash(relative))
			if filepath.Dir(filename) == directory {
				adapter = c
			}
		}
	}
	if adapter == nil {
		t.Fatalf("self-dial adapter package not loaded: %s", directory)
	}
	return adapter
}

func (c selfDials) where(node ast.Node) string {
	position := c.files.Position(node.Pos())
	relative, _ := filepath.Rel(c.root, position.Filename)
	return fmt.Sprintf("%s:%d", filepath.ToSlash(relative), position.Line)
}

// declaredInAdapter reports whether object is declared in a generated adapter.
func (c selfDials) declaredInAdapter(object types.Object) bool {
	for file, generated := range c.generated {
		if generated && file.FileStart <= object.Pos() && object.Pos() < file.FileEnd {
			return true
		}
	}
	return false
}

func (c selfDials) violations() []string {
	var dials []ast.Node
	var violations []string
	seam, _ := c.pkg.Scope().Lookup("gatewayDialOptions").(*types.Func)
	for _, file := range c.parsed {
		if !c.generated[file] {
			continue
		}
		ast.Inspect(file, func(node ast.Node) bool {
			call, ok := node.(*ast.CallExpr)
			if !ok {
				return true
			}
			if seam != nil && c.callsFunc(call, seam) {
				return true
			}
			options, ok := c.dialOptions(call)
			if !ok {
				options, _ = c.forwardedOptions(call)
				if options == nil && c.pluginInterface(call) != nil && len(call.Args) > 0 {
					options = call.Args[len(call.Args)-1]
					if !c.pluginOptions(call, map[*types.Var]bool{}) {
						options = nil
					}
				} else if options != nil {
					_, parameter := c.forwardedOptions(call)
					if !c.optionsUses(parameter, map[*types.Var]bool{}) {
						options = nil
					}
				} else {
					return true
				}
			}
			dials = append(dials, call)
			if seam == nil || !c.fromSeam(options, seam) {
				violations = append(violations, fmt.Sprintf("%s: a generated self-dial must pass gatewayDialOptions(…), or a local defined once from it and used only as dial options or unchanged through a generated same-package forwarder or verified plugin implementation (no aliases, indexing, slicing, unchecked calls or address-taking), as its options", c.where(call)))
			}
			return true
		})
	}
	if len(dials) == 0 {
		return violations
	}
	if reason := c.seamRefusal(seam); reason != "" {
		violations = append(violations, fmt.Sprintf("%s: gatewayDialOptions %s; regenerate with go-grpc 0.1.67 or later", c.where(dials[0]), reason))
	}
	for refusal := range c.refusals {
		violations = append(violations, refusal)
	}
	sort.Strings(violations)
	return violations
}

// dialOptions returns the options argument of a gRPC dial: the spread final
// argument of grpc.NewClient, Dial or DialContext, or the last argument of a
// Register…HandlerFromEndpoint.
func (c selfDials) dialOptions(call *ast.CallExpr) (ast.Expr, bool) {
	selector, ok := call.Fun.(*ast.SelectorExpr)
	if !ok {
		return nil, false
	}
	if c.isGRPC(selector, "NewClient", "Dial", "DialContext") {
		count := 2
		if selector.Sel.Name == "DialContext" {
			count = 3
		}
		if len(call.Args) != count || !call.Ellipsis.IsValid() {
			return nil, true // anything but one spread options argument is refused
		}
		return call.Args[count-1], true
	}
	qualifier, _ := selector.X.(*ast.Ident)
	_, imported := c.info.Uses[qualifier].(*types.PkgName)
	if imported && fromEndpoint.MatchString(selector.Sel.Name) {
		if len(call.Args) == 0 || call.Ellipsis.IsValid() {
			return nil, true
		}
		return call.Args[len(call.Args)-1], true
	}
	return nil, false
}

// isGRPC reports whether selector names one of the given members of the grpc
// package, by the package the qualifier resolves to.
func (c selfDials) isGRPC(selector *ast.SelectorExpr, members ...string) bool {
	qualifier, ok := selector.X.(*ast.Ident)
	if !ok {
		return false
	}
	name, ok := c.info.Uses[qualifier].(*types.PkgName)
	if !ok || name.Imported().Path() != grpcImport {
		return false
	}
	for _, member := range members {
		if selector.Sel.Name == member {
			return true
		}
	}
	return false
}

// callsFunc reports whether expression is a call of function, by identity.
func (c selfDials) callsFunc(expression ast.Expr, function types.Object) bool {
	call, ok := expression.(*ast.CallExpr)
	if !ok {
		return false
	}
	identifier, ok := call.Fun.(*ast.Ident)
	return ok && c.info.Uses[identifier] == function
}

// fromSeam proves both provenance and closed use of the options backing array.
// Forwarder parameters must have callers, and every reference to the function
// must be a direct call carrying proven options. Cycles and function values
// refuse: neither establishes provenance from the seam.
func (c selfDials) fromSeam(options ast.Expr, seam *types.Func) bool {
	return c.fromSeamSeen(options, seam, map[*types.Var]bool{})
}

func (c selfDials) fromSeamSeen(options ast.Expr, seam *types.Func, visiting map[*types.Var]bool) bool {
	if c.callsFunc(options, seam) {
		return true
	}
	identifier, ok := options.(*ast.Ident)
	if !ok {
		return false
	}
	variable, ok := c.info.Uses[identifier].(*types.Var)
	if !ok || variable.Parent() == c.pkg.Scope() || visiting[variable] {
		return false
	}
	visiting[variable] = true
	defer delete(visiting, variable)
	if !c.optionsUses(variable, map[*types.Var]bool{}) {
		return false
	}
	for _, file := range c.parsed {
		for _, declaration := range file.Decls {
			fn, ok := declaration.(*ast.FuncDecl)
			if !ok {
				continue
			}
			function, _ := c.info.Defs[fn.Name].(*types.Func)
			if c.finalParameter(function) != variable {
				continue
			}
			allowed := map[*ast.Ident]bool{}
			valid := true
			for _, source := range c.parsed {
				ast.Inspect(source, func(node ast.Node) bool {
					call, ok := node.(*ast.CallExpr)
					if !ok {
						return true
					}
					callee, id := c.calledFunction(call)
					if callee == function {
						argument, parameter := c.forwardedOptions(call)
						if parameter != variable || !c.fromSeamSeen(argument, seam, visiting) {
							valid = false
						}
						allowed[id] = true
					}
					return true
				})
			}
			for id, object := range c.info.Uses {
				if object == function && !allowed[id] {
					valid = false
				}
			}
			return valid && len(allowed) > 0
		}
	}
	writes := c.writes(variable)
	if len(writes) != 1 {
		return false
	}
	definition, ok := writes[0].(*ast.AssignStmt)
	if !ok || definition.Tok != token.DEFINE || len(definition.Lhs) != len(definition.Rhs) {
		return false
	}
	for i, target := range definition.Lhs {
		if id, ok := target.(*ast.Ident); ok && c.info.Defs[id] == variable {
			return c.callsFunc(definition.Rhs[i], seam)
		}
	}
	return false
}

// calledFunction resolves local functions and concrete methods by object
// identity. Interface dispatch is checked separately against module-wide method
// sets; imported functions and function values are not generated forwarders.
func (c selfDials) calledFunction(call *ast.CallExpr) (*types.Func, *ast.Ident) {
	var id *ast.Ident
	switch fun := call.Fun.(type) {
	case *ast.Ident:
		id = fun
	case *ast.SelectorExpr:
		selection := c.info.Selections[fun]
		if selection == nil || selection.Kind() != types.MethodVal {
			return nil, nil
		}
		id = fun.Sel
	default:
		return nil, nil
	}
	function, _ := c.info.Uses[id].(*types.Func)
	return function, id
}

func (c selfDials) finalParameter(function *types.Func) *types.Var {
	if function == nil || function.Pkg() != c.pkg || !c.declaredInAdapter(function) {
		return nil
	}
	declaration := c.funcDecl(function)
	if declaration == nil || declaration.Body == nil {
		return nil
	}
	// Only options-consuming functions are forwarding candidates.
	fields := declaration.Type.Params.List
	if len(fields) == 0 {
		return nil
	}
	var element ast.Expr
	switch typ := fields[len(fields)-1].Type.(type) {
	case *ast.ArrayType:
		if typ.Len == nil {
			element = typ.Elt
		}
	case *ast.Ellipsis:
		element = typ.Elt
	}
	selector, ok := element.(*ast.SelectorExpr)
	if !ok || !c.isGRPC(selector, "DialOption") {
		return nil
	}
	signature := function.Type().(*types.Signature)
	if signature.Params().Len() == 0 {
		return nil
	}
	return signature.Params().At(signature.Params().Len() - 1)
}

// forwardedOptions admits only an entire final argument, with the declaration's
// exact variadic shape; it never follows a name or assumes an interface's body.
func (c selfDials) forwardedOptions(call *ast.CallExpr) (ast.Expr, *types.Var) {
	function, _ := c.calledFunction(call)
	parameter := c.finalParameter(function)
	if parameter == nil {
		return nil, nil
	}
	signature := function.Type().(*types.Signature)
	if len(call.Args) != signature.Params().Len() || call.Ellipsis.IsValid() != signature.Variadic() {
		return nil, nil
	}
	return call.Args[len(call.Args)-1], parameter
}

// optionsUses recursively checks every occurrence of a slice object. Only
// terminal dials and generated forwarders whose receiving parameter satisfies
// this same rule may consume it. Reads, writes, aliases and escapes all refuse.
func (c selfDials) optionsUses(variable *types.Var, visiting map[*types.Var]bool) bool {
	if visiting[variable] {
		return false
	}
	visiting[variable] = true
	defer delete(visiting, variable)
	allowed := map[*ast.Ident]bool{}
	for _, file := range c.parsed {
		ast.Inspect(file, func(node ast.Node) bool {
			call, ok := node.(*ast.CallExpr)
			if !ok {
				return true
			}
			argument, dial := c.dialOptions(call)
			var parameter *types.Var
			if !dial {
				argument, parameter = c.forwardedOptions(call)
				if argument == nil && c.pluginInterface(call) != nil && len(call.Args) > 0 {
					argument = call.Args[len(call.Args)-1]
				}
			}
			id, ok := argument.(*ast.Ident)
			if ok && c.info.Uses[id] == variable && (dial ||
				(parameter != nil && c.optionsUses(parameter, visiting)) || c.pluginOptions(call, visiting)) {
				allowed[id] = true
			}
			return true
		})
	}
	return len(allowed) > 0 && c.onlyUses(variable, allowed)
}

// pluginInterface resolves the template's named framework.Plugin interface by
// object identity. Its plugin.go template has no generated marker; anonymous or
// same-spelled unrelated interfaces do not acquire this privilege.
func (c selfDials) pluginInterface(call *ast.CallExpr) *types.Interface {
	selector, ok := call.Fun.(*ast.SelectorExpr)
	if !ok {
		return nil
	}
	selection := c.info.Selections[selector]
	if selection == nil || selection.Kind() != types.MethodVal {
		return nil
	}
	named, ok := selection.Recv().(*types.Named)
	if !ok {
		return nil
	}
	owner := c.module[named.Obj().Pkg()]
	if owner == nil || named.Obj() != owner.pkg.Scope().Lookup("Plugin") ||
		!strings.HasSuffix(owner.pkg.Path(), "/pkg/framework") {
		return nil
	}
	iface, _ := named.Underlying().(*types.Interface)
	signature := selection.Obj().Type().(*types.Signature)
	if signature.Params().Len() == 0 {
		return nil
	}
	slice, ok := signature.Params().At(signature.Params().Len() - 1).Type().(*types.Slice)
	if !ok {
		return nil
	}
	option, ok := slice.Elem().(*types.Named)
	if !ok || option.Obj().Pkg() == nil || option.Obj().Pkg().Path() != grpcImport || option.Obj().Name() != "DialOption" {
		return nil
	}
	return iface
}

// Interface dispatch is a closed module-wide proof. Both value and pointer
// method sets participate, including promoted methods and unregistered types.
func (c selfDials) pluginOptions(call *ast.CallExpr, visiting map[*types.Var]bool) bool {
	iface := c.pluginInterface(call)
	if iface == nil {
		return false
	}
	function, _ := c.calledFunction(call)
	if function == nil {
		return false
	}
	signature := function.Type().(*types.Signature)
	if len(call.Args) == 0 || len(call.Args) != signature.Params().Len() ||
		call.Ellipsis.IsValid() != signature.Variadic() {
		return false
	}
	valid := true
	for _, owner := range c.module {
		for concrete := range owner.concreteTypes() {
			if !types.Implements(concrete, iface) {
				continue
			}
			selection := types.NewMethodSet(concrete).Lookup(function.Pkg(), function.Name())
			method := selection.Obj().(*types.Func).Origin()
			bodyOwner := c.module[method.Pkg()]
			if bodyOwner == nil || !bodyOwner.pluginMethodSafe(method, visiting) {
				reason := fmt.Sprintf("%s: %s.%s refuses self-dial options: parameter must be forwarded unchanged to every dial; mutation, replacement, escape or dropping options is forbidden",
					c.where(call), types.TypeString(concrete, nil), function.Name())
				c.refusals[reason] = true
				valid = false
			}
		}
	}
	return valid
}

// Include unnamed structs, aliases and generic instantiations as well as
// declarations. An embedded interface's promoted method has no concrete body
// and therefore refuses, rather than silently escaping the implementation scan.
func (c selfDials) concreteTypes() map[types.Type]bool {
	result := map[types.Type]bool{}
	add := func(typ types.Type) {
		typ = types.Unalias(typ)
		if pointer, ok := typ.(*types.Pointer); ok {
			typ = types.Unalias(pointer.Elem())
		}
		if result[typ] {
			return
		}
		switch typ.(type) {
		case *types.Named, *types.Struct:
			if _, iface := typ.Underlying().(*types.Interface); !iface {
				result[typ] = true
				result[types.NewPointer(typ)] = true
			}
		}
	}
	for _, object := range c.info.Defs {
		if name, ok := object.(*types.TypeName); ok {
			add(name.Type())
		}
	}
	for _, value := range c.info.Types {
		if value.Type != nil {
			add(value.Type)
		}
	}
	return result
}

func (c selfDials) pluginMethodSafe(method *types.Func, visiting map[*types.Var]bool) bool {
	declaration := c.funcDecl(method)
	if declaration == nil || declaration.Body == nil {
		return false
	}
	signature := method.Type().(*types.Signature)
	if signature.Params().Len() == 0 {
		return false
	}
	parameter := signature.Params().At(signature.Params().Len() - 1)
	// A gRPC-only plugin registers no REST endpoint. Admit only a literal no-op,
	// with no calls, aliases or dials hidden behind the unused parameter.
	if len(declaration.Body.List) == 1 {
		if ret, ok := declaration.Body.List[0].(*ast.ReturnStmt); ok && len(ret.Results) == 1 {
			if id, ok := ret.Results[0].(*ast.Ident); ok && c.info.Uses[id] == types.Universe.Lookup("nil") {
				return true
			}
		}
	}
	valid := c.optionsUses(parameter, visiting)
	ast.Inspect(declaration.Body, func(node ast.Node) bool {
		if call, ok := node.(*ast.CallExpr); ok {
			if options, dial := c.dialOptions(call); dial {
				id, ok := options.(*ast.Ident)
				if !ok || c.info.Uses[id] != parameter {
					valid = false
				}
			}
		}
		return true
	})
	return valid
}

// onlyUses refuses any occurrence outside the explicitly permitted positions,
// including reads that can alias a slice or expose its backing array to a call.
func (c selfDials) onlyUses(variable *types.Var, allowed map[*ast.Ident]bool) bool {
	for identifier, object := range c.info.Uses {
		if object == variable && !allowed[identifier] {
			return false
		}
	}
	return true
}

// writes are the statements and expressions that can change variable: an
// assignment to it or to an element of it, an increment, a range over into
// it, and taking its address.
func (c selfDials) writes(variable *types.Var) []ast.Node {
	refers := func(expression ast.Expr) bool {
		for {
			switch e := expression.(type) {
			case *ast.Ident:
				return c.info.Defs[e] == variable || c.info.Uses[e] == variable
			case *ast.IndexExpr:
				expression = e.X
			case *ast.SliceExpr:
				expression = e.X
			case *ast.ParenExpr:
				expression = e.X
			case *ast.StarExpr:
				expression = e.X
			default:
				return false
			}
		}
	}
	var writes []ast.Node
	for _, file := range c.parsed {
		ast.Inspect(file, func(node ast.Node) bool {
			switch n := node.(type) {
			case *ast.AssignStmt:
				for _, target := range n.Lhs {
					if refers(target) {
						writes = append(writes, n)
						break
					}
				}
			case *ast.IncDecStmt:
				if refers(n.X) {
					writes = append(writes, n)
				}
			case *ast.RangeStmt:
				if (n.Key != nil && refers(n.Key)) || (n.Value != nil && refers(n.Value)) {
					writes = append(writes, n)
				}
			case *ast.UnaryExpr:
				if n.Op == token.AND && refers(n.X) {
					writes = append(writes, n)
				}
			case *ast.ValueSpec:
				for _, name := range n.Names {
					if c.info.Defs[name] == variable {
						writes = append(writes, n)
					}
				}
			}
			return true
		})
	}
	return writes
}

// seamRefusal says what is wrong with the package's gatewayDialOptions, or ""
// when it refuses the environment proxy and ends on the loopback transport.
func (c selfDials) seamRefusal(seam *types.Func) string {
	if seam == nil {
		return "is not declared in this package"
	}
	if !c.declaredInAdapter(seam) {
		return "is not declared in a generated adapter"
	}
	declaration := c.funcDecl(seam)
	if declaration == nil || declaration.Body == nil || len(declaration.Body.List) == 0 {
		return "has no body"
	}
	// Reject these operations anywhere in the body, including nested expressions
	// or closures; neither copy nor indexed writes can preserve the proof.
	mutation := false
	ast.Inspect(declaration.Body, func(node ast.Node) bool {
		switch n := node.(type) {
		case *ast.AssignStmt:
			for _, target := range n.Lhs {
				if _, ok := target.(*ast.Ident); !ok {
					mutation = true
				}
			}
		case *ast.CallExpr:
			if c.isBuiltin(n.Fun, "copy") {
				mutation = true
			}
		}
		return true
	})
	if mutation {
		return "contains an indexed, sliced or indirect assignment, or copy"
	}
	statements := declaration.Body.List
	final, ok := statements[len(statements)-1].(*ast.ReturnStmt)
	if !ok || len(final.Results) != 1 {
		return "does not end by returning its options"
	}
	built, ok := final.Results[0].(*ast.CallExpr)
	if !ok || !c.isBuiltin(built.Fun, "append") || built.Ellipsis.IsValid() || len(built.Args) != 2 {
		return "does not return append(options, grpc.WithTransportCredentials(loopbackTransport{…}))"
	}
	if reason := c.loopbackRefusal(built.Args[1]); reason != "" {
		return reason
	}
	identifier, ok := built.Args[0].(*ast.Ident)
	options, _ := c.info.Uses[identifier].(*types.Var)
	if !ok || options == nil || options.Parent() == c.pkg.Scope() {
		return "does not return a local options slice"
	}
	noProxy := false
	allowed := map[*ast.Ident]bool{identifier: true}
	for _, statement := range statements[:len(statements)-1] {
		assignment, ok := statement.(*ast.AssignStmt)
		if !ok {
			return "sets its options outside straight-line assignments"
		}
		if len(assignment.Lhs) != 1 || len(assignment.Rhs) != 1 {
			return "must define or append its options in single-value assignments"
		}
		id, ok := assignment.Lhs[0].(*ast.Ident)
		if !ok || (c.info.Defs[id] != options && c.info.Uses[id] != options) {
			return "assigns something other than its options slice"
		}
		allowed[id] = true
		value := assignment.Rhs[0]
		switch {
		case assignment.Tok == token.DEFINE && c.info.Defs[id] == options:
			noProxy = c.holdsNoProxy(value)
		case assignment.Tok == token.ASSIGN:
			grown, ok := value.(*ast.CallExpr)
			var first *ast.Ident
			if ok && len(grown.Args) > 0 {
				first, _ = grown.Args[0].(*ast.Ident)
			}
			if !ok || !c.isBuiltin(grown.Fun, "append") || first == nil || c.info.Uses[first] != options {
				return "replaces its options rather than appending to them"
			}
			allowed[first] = true
		default:
			return "writes its options other than by definition or append"
		}
	}
	if !c.onlyUses(options, allowed) {
		return "uses its options outside the permitted append and return positions"
	}
	if !noProxy {
		return "does not define its options from a slice literal holding grpc.WithNoProxy()"
	}
	return ""
}

func (c selfDials) funcDecl(function *types.Func) *ast.FuncDecl {
	for _, file := range c.parsed {
		for _, declaration := range file.Decls {
			if fn, ok := declaration.(*ast.FuncDecl); ok && c.info.Defs[fn.Name] == function {
				return fn
			}
		}
	}
	return nil
}

func (c selfDials) isBuiltin(expression ast.Expr, name string) bool {
	identifier, ok := expression.(*ast.Ident)
	if !ok {
		return false
	}
	builtin, ok := c.info.Uses[identifier].(*types.Builtin)
	return ok && builtin.Name() == name
}

// holdsNoProxy reports whether value is a slice literal with grpc.WithNoProxy()
// among its elements.
func (c selfDials) holdsNoProxy(value ast.Expr) bool {
	literal, ok := value.(*ast.CompositeLit)
	if !ok {
		return false
	}
	for _, element := range literal.Elts {
		call, ok := element.(*ast.CallExpr)
		if !ok || len(call.Args) != 0 {
			continue
		}
		if selector, ok := call.Fun.(*ast.SelectorExpr); ok && c.isGRPC(selector, "WithNoProxy") {
			return true
		}
	}
	return false
}

// loopbackRefusal says what is wrong with the option appended last, or "" when
// it is grpc.WithTransportCredentials(loopbackTransport{…}) and that type and
// its ClientHandshake are the generated ones.
func (c selfDials) loopbackRefusal(option ast.Expr) string {
	const want = "does not append grpc.WithTransportCredentials(loopbackTransport{…}) last"
	call, ok := option.(*ast.CallExpr)
	if !ok || len(call.Args) != 1 {
		return want
	}
	selector, ok := call.Fun.(*ast.SelectorExpr)
	if !ok || !c.isGRPC(selector, "WithTransportCredentials") {
		return want
	}
	literal, ok := call.Args[0].(*ast.CompositeLit)
	if !ok {
		return want
	}
	typeName, ok := literal.Type.(*ast.Ident)
	if !ok {
		return want
	}
	transport, ok := c.info.Uses[typeName].(*types.TypeName)
	if !ok || transport.Name() != "loopbackTransport" || transport.Parent() != c.pkg.Scope() || !c.declaredInAdapter(transport) {
		return "appends credentials last that are not the generated loopbackTransport"
	}
	named, ok := transport.Type().(*types.Named)
	if !ok {
		return "appends credentials last that are not the generated loopbackTransport"
	}
	for i := 0; i < named.NumMethods(); i++ {
		if method := named.Method(i); method.Name() == "ClientHandshake" && c.declaredInAdapter(method) {
			return ""
		}
	}
	return "appends a loopbackTransport whose ClientHandshake is not generated"
}

// emptyPackages imports every path as an empty, complete package named by its
// last path element (grpc for google.golang.org/grpc).
type emptyPackages struct{}

func (emptyPackages) Import(importPath string) (*types.Package, error) {
	name := importPath[strings.LastIndex(importPath, "/")+1:]
	if importPath == grpcImport {
		name = "grpc"
	}
	pkg := types.NewPackage(importPath, name)
	pkg.MarkComplete()
	return pkg, nil
}

