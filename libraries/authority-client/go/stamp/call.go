package stamp

import (
	"crypto/ed25519"
	"crypto/rand"
	"crypto/sha256"
	"encoding/base64"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"strings"
	"time"

	"google.golang.org/grpc/metadata"
)

// Lifetime bounds how long an admitted call may start. It does not limit a stream's duration.
const Lifetime = 30 * time.Second

// Call is a signed, single-use admission, independent of the Work Context's replay policy.
// The array encoding and domain separate this protocol from Work Context signatures.
type Call struct {
	Method   string
	Audience string
	Digest   string
	Nonce    string
	Issued   int64
	Expires  int64
}

// Signer holds a service-scoped seed generated by Codefly. Never deliver it to a verifier.
type Signer struct{ key ed25519.PrivateKey }

func NewSigner(seed string) (*Signer, error) {
	raw, err := hex.DecodeString(seed)
	if err != nil || len(raw) != ed25519.SeedSize {
		return nil, errors.New("hop: signing seed must be 32 Codefly-generated bytes in hex")
	}
	return &Signer{key: ed25519.NewKeyFromSeed(raw)}, nil
}

func (s *Signer) PublicKey() string { return hex.EncodeToString(s.key.Public().(ed25519.PublicKey)) }

// Sign is called only after the authority admits the exact method and audience.
func (s *Signer) Sign(token, method, audience string, now time.Time, tokenExpiry int64) (string, error) {
	if s == nil || len(s.key) != ed25519.PrivateKeySize || token == "" || method == "" || audience == "" {
		return "", errors.New("hop: signing needs a token, exact method, audience and signing key")
	}
	expires := now.Add(Lifetime).Unix()
	if tokenExpiry < expires {
		expires = tokenExpiry
	}
	if expires <= now.Unix() {
		return "", errors.New("hop: cannot stamp an expired context")
	}
	nonce := make([]byte, 32)
	if _, err := rand.Read(nonce); err != nil {
		return "", errors.New("hop: cannot generate call nonce")
	}
	digest := sha256.Sum256([]byte(token))
	payload, err := json.Marshal([]any{"codefly-hop-v1", method, audience, hex.EncodeToString(digest[:]), hex.EncodeToString(nonce), now.Unix(), expires})
	if err != nil {
		return "", err
	}
	return base64.RawURLEncoding.EncodeToString(payload) + "." + base64.RawURLEncoding.EncodeToString(ed25519.Sign(s.key, payload)), nil
}

// Check authenticates the binding before any keys lookup or replay-store write.
// publicKey is trusted delivery configuration, never read from incoming metadata.
func Check(md metadata.MD, publicKey, method, audience string, now time.Time) (Call, error) {
	fail := func(reason string) (Call, error) { return Call{}, fmt.Errorf("hop: %s", reason) }
	one := func(key string) string {
		v := md.Get(key)
		if len(v) != 1 {
			return ""
		}
		return v[0]
	}
	encoded := one("x-codefly-hop-proof")
	parts := strings.Split(encoded, ".")
	pub, err := hex.DecodeString(publicKey)
	if err != nil || len(pub) != ed25519.PublicKeySize || len(parts) != 2 || len(encoded) > 8192 {
		return fail("invalid signed hop proof")
	}
	payload, err := base64.RawURLEncoding.DecodeString(parts[0])
	if err != nil || base64.RawURLEncoding.EncodeToString(payload) != parts[0] {
		return fail("noncanonical hop proof")
	}
	signature, err := base64.RawURLEncoding.DecodeString(parts[1])
	if err != nil || base64.RawURLEncoding.EncodeToString(signature) != parts[1] || !ed25519.Verify(pub, payload, signature) {
		return fail("hop proof signature does not verify")
	}
	var fields []json.RawMessage
	if json.Unmarshal(payload, &fields) != nil || len(fields) != 7 {
		return fail("malformed hop proof")
	}
	var domain string
	var call Call
	for n, dst := range []any{&domain, &call.Method, &call.Audience, &call.Digest, &call.Nonce, &call.Issued, &call.Expires} {
		if string(fields[n]) == "null" || json.Unmarshal(fields[n], dst) != nil {
			return fail("malformed hop proof field")
		}
	}
	if domain != "codefly-hop-v1" {
		return fail("unknown hop proof version")
	}
	if method == "" || call.Method != method {
		return fail("hop proof method mismatch")
	}
	if audience == "" || call.Audience != audience {
		return fail("hop proof audience mismatch")
	}
	if call.Issued < 0 || call.Expires < 0 || call.Issued > now.Unix() || call.Expires <= now.Unix() || call.Expires <= call.Issued || call.Expires-call.Issued > int64(Lifetime/time.Second) {
		return fail("hop proof expired or outside its validity window")
	}
	nonce, err := hex.DecodeString(call.Nonce)
	if err != nil || len(nonce) != 32 || hex.EncodeToString(nonce) != call.Nonce {
		return fail("invalid hop proof nonce")
	}
	token := one("x-codefly-work-context")
	digest := sha256.Sum256([]byte(token))
	if token == "" || call.Digest != hex.EncodeToString(digest[:]) || one("x-codefly-hop-context") != call.Digest {
		return fail("hop proof token digest mismatch")
	}
	if len(md.Get("x-codefly-hop-advisory")) != 0 {
		return fail("hop proof cannot authorize an advisory refusal")
	}
	return call, nil
}

// ReplayKey is globally namespaced by signing key and random nonce, not by method:
// even an accidental nonce reuse on another method must not authorize another call.
func (c Call) ReplayKey(publicKey string) string {
	return "codefly-hop-v1:" + publicKey + ":" + c.Nonce
}
