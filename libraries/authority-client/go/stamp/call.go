package stamp

import (
	"crypto/ed25519"
	"crypto/rand"
	"crypto/sha256"
	"encoding/base64"
	"encoding/hex"
	"encoding/json"
	"errors"
	"strings"
	"time"

	authorityv1 "github.com/codefly-dev/authority/libraries/authority-client/go/gen/host/authority/v1"
	"github.com/codefly-dev/authority/libraries/authority-client/go/refusal"
	"google.golang.org/grpc/metadata"
)

// Lifetime bounds how long an admitted call may start. It does not limit a stream's duration.
const Lifetime = 30 * time.Second

// Skew is the clock difference tolerated between the hop that signed an
// admission and the verifier judging it. Without it a verifier lagging the hop
// by a fraction of a second refuses genuine calls whenever the signing instant
// falls just after a second boundary, and the refusal reads as an expiry.
//
// It widens two bounds and no others: an admission may be issued up to Skew
// ahead of the verifier's clock, and remains admissible until Skew past its
// expiry. The signed span itself (expires - issued) is still capped at Lifetime
// exactly, so the allowance cannot be used to mint a longer-lived admission.
// Go, Python and TypeScript apply the same value, and a replay reservation is
// retained to expiry plus Skew so a store evicting on its own clock cannot
// release a nonce a lagging verifier would still accept.
const Skew = 2 * time.Second

// Call is a signed, single-use admission, independent of the Work Context's replay policy.
// The array encoding and domain separate this protocol from Work Context signatures.
type Call struct {
	Method   string
	Audience string
	Digest   string
	Nonce    string
	Issued   int64
	Expires  int64
}

// Signer holds a service-scoped seed generated by Codefly. Never deliver it to a verifier.
type Signer struct{ key ed25519.PrivateKey }

func NewSigner(seed string) (*Signer, error) {
	raw, err := hex.DecodeString(seed)
	if err != nil || len(raw) != ed25519.SeedSize {
		return nil, errors.New("hop: signing seed must be 32 Codefly-generated bytes in hex")
	}
	return &Signer{key: ed25519.NewKeyFromSeed(raw)}, nil
}

func (s *Signer) PublicKey() string { return hex.EncodeToString(s.key.Public().(ed25519.PublicKey)) }

// Sign is called only after the authority admits the exact method and audience.
func (s *Signer) Sign(token, method, audience string, now time.Time, tokenExpiry int64) (string, error) {
	if s == nil || len(s.key) != ed25519.PrivateKeySize || token == "" || method == "" || audience == "" {
		return "", errors.New("hop: signing needs a token, exact method, audience and signing key")
	}
	expires := now.Add(Lifetime).Unix()
	if tokenExpiry < expires {
		expires = tokenExpiry
	}
	if expires <= now.Unix() {
		return "", errors.New("hop: cannot stamp an expired context")
	}
	nonce := make([]byte, 32)
	if _, err := rand.Read(nonce); err != nil {
		return "", errors.New("hop: cannot generate call nonce")
	}
	digest := sha256.Sum256([]byte(token))
	payload, err := json.Marshal([]any{"codefly-hop-v1", method, audience, hex.EncodeToString(digest[:]), hex.EncodeToString(nonce), now.Unix(), expires})
	if err != nil {
		return "", err
	}
	return base64.RawURLEncoding.EncodeToString(payload) + "." + base64.RawURLEncoding.EncodeToString(ed25519.Sign(s.key, payload)), nil
}

// Check authenticates the binding before any keys lookup or replay-store write.
// publicKey is one of the authority's published admission keys (SignedBy
// chooses it), never read from incoming metadata.
// Every refusal is a caller-safe refusal.Reason: it names no proof, token,
// digest or nonce, and callers read its code with errors.As.
func Check(md metadata.MD, publicKey, method, audience string, now time.Time) (Call, error) {
	fail := func(reason refusal.Reason) (Call, error) { return Call{}, reason }
	one := func(key string) string {
		v := md.Get(key)
		if len(v) != 1 {
			return ""
		}
		return v[0]
	}
	payload, signature, ok := proof(md)
	pub, err := hex.DecodeString(publicKey)
	if !ok || err != nil || len(pub) != ed25519.PublicKeySize || !ed25519.Verify(pub, payload, signature) {
		return fail(refusal.StampProof)
	}
	var fields []json.RawMessage
	if json.Unmarshal(payload, &fields) != nil || len(fields) != 7 {
		return fail(refusal.StampProof)
	}
	var domain string
	var call Call
	for n, dst := range []any{&domain, &call.Method, &call.Audience, &call.Digest, &call.Nonce, &call.Issued, &call.Expires} {
		if string(fields[n]) == "null" || json.Unmarshal(fields[n], dst) != nil {
			return fail(refusal.StampProof)
		}
	}
	if domain != "codefly-hop-v1" {
		return fail(refusal.StampProof)
	}
	if method == "" || call.Method != method {
		return fail(refusal.StampMethod)
	}
	if audience == "" || call.Audience != audience {
		return fail(refusal.StampAudience)
	}
	seconds, skew := now.Unix(), int64(Skew/time.Second)
	switch {
	case call.Issued < 0 || call.Expires < 0:
		return fail(refusal.StampWindow)
	case call.Issued > seconds+skew:
		// Further ahead than a clock difference explains: its own reason, so a
		// verifier running behind is not diagnosed as an expiry.
		return fail(refusal.StampIssued)
	case call.Expires+skew <= seconds:
		return fail(refusal.StampWindow)
	case call.Expires <= call.Issued || call.Expires-call.Issued > int64(Lifetime/time.Second):
		// The signed span is judged without the allowance.
		return fail(refusal.StampWindow)
	}
	nonce, err := hex.DecodeString(call.Nonce)
	if err != nil || len(nonce) != 32 || hex.EncodeToString(nonce) != call.Nonce {
		return fail(refusal.StampProof)
	}
	// A missing or repeated token is the stamp binding nothing; a token that
	// does not hash to the signed digest, or a context key disagreeing with
	// it, is a swap. The two are distinct refusals.
	tokens := md.Get("x-codefly-work-context")
	if len(tokens) != 1 || tokens[0] == "" {
		return fail(refusal.StampToken)
	}
	digest := sha256.Sum256([]byte(tokens[0]))
	if call.Digest != hex.EncodeToString(digest[:]) || one("x-codefly-hop-context") != call.Digest {
		return fail(refusal.StampDigest)
	}
	if len(md.Get("x-codefly-hop-advisory")) != 0 {
		return fail(refusal.StampAdvisory)
	}
	return call, nil
}

// proof is the one admission md carries, split into its signed payload and
// signature, each in canonical encoding; ok is false for anything else.
func proof(md metadata.MD) (payload, signature []byte, ok bool) {
	values := md.Get("x-codefly-hop-proof")
	if len(values) != 1 || len(values[0]) > 8192 {
		return nil, nil, false
	}
	parts := strings.Split(values[0], ".")
	if len(parts) != 2 {
		return nil, nil, false
	}
	payload, err := base64.RawURLEncoding.DecodeString(parts[0])
	if err != nil || base64.RawURLEncoding.EncodeToString(payload) != parts[0] {
		return nil, nil, false
	}
	signature, err = base64.RawURLEncoding.DecodeString(parts[1])
	if err != nil || base64.RawURLEncoding.EncodeToString(signature) != parts[1] {
		return nil, nil, false
	}
	return payload, signature, true
}

// SignedBy is which of the published admission keys (hex) the admission md
// carries is signed by, or "" when it is signed by none of them. It
// authenticates only the signature: Check, given the key it names, judges the
// rest. A verifier trusts more than one key while a hop's key rotates.
func SignedBy(md metadata.MD, publicKeys []string) string {
	payload, signature, ok := proof(md)
	if !ok {
		return ""
	}
	for _, key := range publicKeys {
		pub, err := hex.DecodeString(key)
		if err == nil && len(pub) == ed25519.PublicKeySize && ed25519.Verify(pub, payload, signature) {
			return key
		}
	}
	return ""
}

// Purpose is what a published admission key verifies: Keys carries the hop's
// keys in admission_keys with this purpose, never among the Work Context keys.
const Purpose = "hop-admission"

// Published is the signer's public key as the authority publishes it in Keys'
// admission_keys: Ed25519, this purpose, and a key id derived from the key, so
// the same seed always publishes the same entry.
func (s *Signer) Published() *authorityv1.PublicKey {
	public := s.key.Public().(ed25519.PublicKey)
	sum := sha256.Sum256(public)
	return &authorityv1.PublicKey{KeyId: "hop-" + hex.EncodeToString(sum[:8]), Algorithm: "Ed25519", PublicKey: public, Purpose: Purpose}
}

// ReplayKey is globally namespaced by signing key and random nonce, not by method:
// even an accidental nonce reuse on another method must not authorize another call.
func (c Call) ReplayKey(publicKey string) string {
	return "codefly-hop-v1:" + publicKey + ":" + c.Nonce
}
